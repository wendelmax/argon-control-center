use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Language {
    PtBr,
    EnUs,
}

impl Language {
    pub fn code(&self) -> &'static str {
        match self {
            Language::PtBr => "PT-BR",
            Language::EnUs => "EN-US",
        }
    }

    pub fn label(&self) -> &'static str {
        match self {
            Language::PtBr => "🇧🇷 PT-BR",
            Language::EnUs => "🇺🇸 EN-US",
        }
    }
}

